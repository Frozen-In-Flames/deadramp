"""Reporting and export formatting.

A query result is a dict ``{columns, rows, row_count}`` whose rows are
dicts keyed by column name (list rows are also accepted positionally).
Reports compose such results into a standalone HTML document; all text
taken from the data is HTML-escaped, while chart SVGs (already escaped
at render time) are embedded as markup.
"""

import csv
import html
import io
import json

from .errors import ValidationError


def _row_values(result, row):
    columns = result.get("columns") or []
    if isinstance(row, dict):
        return [row.get(col) for col in columns]
    if isinstance(row, (list, tuple)):
        return list(row)
    raise ValidationError("result rows must be objects or arrays")


def _cell_text(value):
    if value is None:
        return ""
    return str(value)


def result_to_csv(result):
    """Serialize a query result to CSV text (header row plus data)."""
    if not isinstance(result, dict):
        raise ValidationError("result must be an object")
    output = io.StringIO()
    writer = csv.writer(output, lineterminator="\n")
    columns = result.get("columns") or []
    writer.writerow(columns)
    for row in result.get("rows") or []:
        writer.writerow([_cell_text(v) for v in _row_values(result, row)])
    return output.getvalue()


def result_to_json(result):
    """Serialize a query result to a JSON string."""
    if not isinstance(result, dict):
        raise ValidationError("result must be an object")
    return json.dumps(result, indent=2)


def _table_html(result):
    columns = result.get("columns") or []
    parts = ["<table>", "<thead><tr>"]
    for col in columns:
        parts.append("<th>%s</th>" % (html.escape(str(col)),))
    parts.append("</tr></thead>")
    parts.append("<tbody>")
    for row in result.get("rows") or []:
        parts.append("<tr>")
        for value in _row_values(result, row):
            parts.append("<td>%s</td>" % (html.escape(_cell_text(value)),))
        parts.append("</tr>")
    parts.append("</tbody></table>")
    return "".join(parts)


def report_html(title, sections):
    """Compose a full HTML report from titled sections.

    Each section is ``{heading, table, chart_svg}`` where ``table`` is a
    query result (or None) and ``chart_svg`` is an SVG string (or None).
    """
    if sections is None:
        sections = []
    parts = [
        "<!DOCTYPE html>",
        '<html lang="en">',
        "<head>",
        '<meta charset="utf-8">',
        "<title>%s</title>" % (html.escape(str(title)),),
        "</head>",
        "<body>",
        "<h1>%s</h1>" % (html.escape(str(title)),),
    ]
    for section in sections:
        if not isinstance(section, dict):
            raise ValidationError("each report section must be an object")
        parts.append("<section>")
        heading = section.get("heading", "")
        parts.append("<h2>%s</h2>" % (html.escape(str(heading)),))
        table = section.get("table")
        if table is not None:
            parts.append(_table_html(table))
        chart = section.get("chart_svg")
        if chart:
            # Chart SVGs are generated by charts.chart_svg, which escapes
            # all data-derived text; embed the markup as-is.
            parts.append(str(chart))
        parts.append("</section>")
    parts.append("</body>")
    parts.append("</html>")
    return "\n".join(parts)
